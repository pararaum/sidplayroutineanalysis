"""Export a song as a ca65 assembler source file.

The file contains the NinjaTracker V2.04 play routine (Cadaver, 2013, ported to
ca65) and the packed song data with symbolic addresses, so it can be assembled
with `ca65` and placed anywhere by `ld65`.  Entry points (all exported):

    nt_init      A = subtune number (0-based): selects the song data and starts the subtune
    nt_play      call once per frame
    nt_playsfx   start a sound effect (see the play routine)
    nt_data      the packed song data, nt_numsongs the number of subtunes
    nt_music, nt_newmusic, nt_playsong   the play routine's own entry points

With `player=False` only the song is written; its entry points are named after
`prefix` (`<prefix>_init`, `<prefix>_data`, `<prefix>_numsongs`) and it imports
`nt_newmusic` and `nt_playsong`, which come from a file exported with the play
routine.  The song's hard-restart / first-wave settings live in the play
routine, so the player file has to be exported with the same settings.
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import List

from .model import Song, note_name
from .packed import Layout, PackError, layout

PLAYER_SRC = Path(__file__).with_name("nt2play.s")


def _clean(text: str) -> str:
    return "".join(c if 32 <= ord(c) < 127 else "?" for c in text)[:60]


def _bytes(lines: List[str], data: bytes, comment: str = "", width: int = 16) -> None:
    if not data:
        return
    for i in range(0, len(data), width):
        chunk = ",".join(f"${b:02X}" for b in data[i:i + width])
        lines.append(f"        .byte {chunk}" + (f"    ; {comment}" if i == 0 and comment else ""))


def _row_text(row) -> str:
    if row.note is not None:
        what = note_name(row.note)
    elif row.gate == "off":
        what = "---"
    elif row.gate == "on":
        what = "+++"
    else:
        what = "..."
    if row.cmd is not None:
        what += f" cmd {row.cmd:02X}" + (" legato" if row.legato else "")
    if row.dur is not None:
        what += f" dur {row.dur}"
    return what


def export_asm(song: Song, *, prefix: str = "nt", player: bool = True,
               code_segment: str = "CODE", data_segment: str = "RODATA") -> str:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", prefix):
        raise ValueError(f"bad symbol prefix {prefix!r}")
    lay: Layout = layout(song)
    s = lay.song
    nsongs = len(lay.tracks)
    if nsongs == 0:
        raise PackError("the song has no subtune with data")
    p = prefix
    out: List[str] = []
    w = out.append

    w(f"; {_clean(song.title) or 'Untitled'}")
    if song.author:
        w(f"; by {_clean(song.author)}")
    if song.released:
        w(f"; {_clean(song.released)}")
    w("; Generated by ntedit (NinjaTracker V2 song export, ca65 syntax).")
    w(";")
    w("; Usage:")
    w(";           lda #0            ; subtune number, 0-based")
    w(f";           jsr {p}_init")
    w(";           ...               ; then once per frame (raster IRQ / PAL 50 Hz):")
    w(f";           jsr {'nt_play' if player else 'nt_music'}")
    w(";")
    w("; The play routine modifies its own code and must be placed in RAM. It needs two")
    w(f"; zero page bytes (segment ZEROPAGE, allocated by the linker). {p}_init must not run")
    w("; while the IRQ calls the play routine.")
    if not player:
        w(f"; Data only. The play routine must be built with NT_HRPARAM = ${song.hr_param & 0xFF:02X} and")
        w(f"; NT_FIRSTWAVE = ${song.first_wave & 0xFF:02X} (export a song with these settings with the player included).")
    w("")
    w("        .setcpu \"6502\"")
    exports = [f"{p}_init", f"{p}_data", f"{p}_numsongs"]
    if player:
        exports += ["nt_play", "nt_music", "nt_playsong", "nt_newmusic", "nt_playsfx"]
    w(f"        .export {', '.join(exports)}")
    if not player:
        w("        .import nt_newmusic, nt_playsong")
    w("")
    w(f"{p}_numsongs = {nsongs}")
    w("")
    w(f'        .segment "{code_segment}"')
    w("")
    w(f"{p}_init:")
    w("        pha")
    w(f"        lda #<{p}_data")
    w(f"        ldx #>{p}_data")
    w("        jsr nt_newmusic")
    w("        pla")
    w("        jmp nt_playsong")
    w("")
    if player:
        w("; ---------------------------------------------------------------------------")
        w("; Play routine settings for this song")
        w("; ---------------------------------------------------------------------------")
        w(f"NT_HRPARAM         = ${song.hr_param & 0xFF:02X}    ; SR value written during the hard restart")
        w(f"NT_FIRSTWAVE       = ${song.first_wave & 0xFF:02X}    ; waveform written on the first frame of a note")
        w("")
        w("nt_play = nt_music")
        w("")
        text = PLAYER_SRC.read_text()
        w(text.rstrip("\n"))
        w("")
    w("; ---------------------------------------------------------------------------")
    w("; Song data")
    w("; ---------------------------------------------------------------------------")
    w(f'        .segment "{data_segment}"')
    w("")
    w(f"{p}_data:")
    h = lay.header
    w(f"        .byte ${h[0]:02X},${h[1]:02X},${h[2]:02X},${h[3]:02X},${h[4]:02X},${h[5]:02X}"
      "    ; table lengths wave/pulse/filter, commands, commands incl. legato-only, patterns")
    for name, blk in lay.tables:
        _bytes(out, blk, name)
    npat = len(lay.patterns)
    if npat:
        lo = ",".join(f"<{p}_pat{i + 1}" for i in range(npat))
        hi = ",".join(f">{p}_pat{i + 1}" for i in range(npat))
        w(f"        .byte {lo}    ; pattern addresses, low bytes")
        w(f"        .byte {hi}    ; pattern addresses, high bytes")
    for i, (blob, (l1, l2, _)) in enumerate(zip(lay.tracks, lay.lens)):
        w(f"        .word {p}_trk{i}    ; subtune {i}: track data")
        w(f"        .byte $00,${l1:02X},${(l1 + l2) & 0xFF:02X}    ; start positions of the three voices")
    w("")
    for i, pat in enumerate(s.patterns[:npat]):
        w(f"{p}_pat{i + 1}:" + ("    ; (empty)" if not pat.rows else ""))
        for row in pat.rows:
            _bytes(out, row.encode(), _row_text(row))
        if pat.rows:
            w("        .byte $00    ; end of pattern")
    w("")
    from .packed import encode_tracks  # same encoder as the binary export
    for i, st in enumerate(s.subtunes[:nsongs]):
        w(f"{p}_trk{i}:")
        if st.is_empty():
            continue
        blob, lens = encode_tracks(st)
        pos = 0
        emitted = bytearray()
        for v, tr in enumerate(st.tracks):
            w(f"        ; subtune {i}, voice {v + 1}")
            offs, seg = [], bytearray()
            for it in tr.items:
                offs.append(len(seg))
                b = it.encode()
                seg.append(b)
                what = f"pattern {it.value:02X}" if it.kind == "pat" else f"transpose {it.value:+d}"
                w(f"        .byte ${b:02X}    ; {what}")
            tgt = pos + offs[tr.loop]
            w(f"        .byte $00,${tgt:02X}    ; loop to position {tgt:02X}")
            seg += bytes([0, tgt])
            emitted += seg
            pos += len(seg)
        assert bytes(emitted) == blob
    w("")
    return "\n".join(out)


def write_asm(song: Song, path, **kw) -> None:
    Path(path).write_text(export_asm(song, **kw))


def main(argv=None) -> None:
    import argparse
    from .project import load_any
    ap = argparse.ArgumentParser(description="Export a song as a ca65 source file")
    ap.add_argument("song", help=".nt2, .nt2.json, .bin or .sid file")
    ap.add_argument("output", help="assembler file to write")
    ap.add_argument("--no-player", action="store_true", help="song data only")
    ap.add_argument("--prefix", default="nt")
    a = ap.parse_args(argv)
    write_asm(load_any(a.song), a.output, prefix=a.prefix, player=not a.no_player)


if __name__ == "__main__":
    main()
